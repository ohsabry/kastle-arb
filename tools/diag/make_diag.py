#!/usr/bin/env python3
"""Generates the temporary measuring build, tools/diag/kastleArp.ino, from kastl-arb.ino.

It plays exactly like kastl-arb.ino and also records into EEPROM:
  byte 63      0xA5 once logging has started (cleared at every power-up)
  bytes 64-95  one bit per NOTE reading seen, 0-255
  bytes 96-99  one bit per note window that actually sounded, 0-28 (room for 32)
Run: python3 -I tools/diag/make_diag.py
"""
import os

here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, '..', '..', 'kastl-arb.ino'), encoding='utf-8', newline='').read()
nl = '\r\n' if '\r\n' in src else '\n'
s = src.replace('\r\n', '\n')


def sub(old, new):
    global s
    assert s.count(old) == 1, (s.count(old), old)
    s = s.replace(old, new)


sub('  KASTLE ARP - MAQAM BAYATI VERSION', '''  MEASURING BUILD - TEMPORARY, GENERATED BY tools/diag/make_diag.py, NOT FOR KEEPS
  plays like kastl-arb.ino and logs NOTE readings and the notes that sound into EEPROM

  KASTLE ARP - MAQAM BAYATI VERSION''')
sub('uint8_t root, lastRoot;\n', '''uint8_t root, lastRoot;
uint8_t adcSeen[32];  //measuring: one bit per NOTE reading seen
uint8_t noteSeen[4];  //measuring: one bit per note window that sounded
''')
sub('uint8_t chord;\nvoid loop() {', '''void logBit(uint8_t *bits, uint8_t base, uint8_t v) {
  uint8_t bit = 1 << (v & 7);
  if (!(bits[v >> 3] & bit)) {
    bits[v >> 3] |= bit;
    EEPROM.write(base + (v >> 3), bits[v >> 3]);
  }
}

uint8_t chord;
void loop() {''')
sub('  //serial for debugging only', '''  for (uint8_t i = 0; i < 36; i++) EEPROM.write(64 + i, 0);
  for (uint8_t i = 0; i < 32; i++) adcSeen[i] = 0;
  for (uint8_t i = 0; i < 4; i++) noteSeen[i] = 0;
  EEPROM.write(63, 0xA5);

  //serial for debugging only''')
sub('  else { // NORMAL LOOP\n', '''  else { // NORMAL LOOP
    logBit(adcSeen, 64, pitchAverage);
''')
# log the window whenever setNote() actually runs in the normal loop, which is when it sounds
sub('''        if (decayVolume < 100) {
          setNote( pitch);''', '''        if (decayVolume < 100) {
          setNote( pitch);
          logBit(noteSeen, 96, window);''')
sub('''      //when decay CW trigger envelope at every pitch change
      setNote( pitch);''', '''      //when decay CW trigger envelope at every pitch change
      setNote( pitch);
      logBit(noteSeen, 96, window);''')
open(os.path.join(here, 'kastleArp.ino'), 'w', encoding='utf-8', newline='').write(s.replace('\n', nl))
print('wrote tools/diag/kastleArp.ino')
